// Regenerates src/app-logos-extra.ts: `npm --prefix frontend run logos` (after bumping the icon-set packages).
// Copies only the listed icon bodies (sanitized) out of the Iconify JSON sets.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
// app id -> [iconify package, icon name]
const WANTED = {
  adobe_marketing_agent_mcp: ['logos', 'adobe-icon'],
  amplitude_mcp: ['logos', 'amplitude-icon'],
  customerio_mcp: ['logos', 'customerio-icon'],
  higgsfield_mcp: ['logos', 'higgsfield-icon'],
  slack: ['logos', 'slack-icon'],
  canva_mcp: ['devicon', 'canva'],
}
const TAGS = new Set(['svg', 'g', 'path', 'circle', 'rect', 'polygon', 'ellipse', 'lineargradient', 'radialgradient', 'stop', 'defs'])
const ATTRS = new Set(['d', 'fill', 'fill-rule', 'fill-opacity', 'clip-rule', 'opacity', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'stroke-opacity', 'transform', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'points', 'id', 'offset', 'stop-color', 'stop-opacity', 'x1', 'y1', 'x2', 'y2', 'gradientunits', 'gradienttransform', 'fx', 'fy'])

function sanitize(body, label) {
  if (/<!|<\?|javascript:/i.test(body)) throw new Error(`${label}: forbidden markup`)
  const tagRe = /<\/?([a-zA-Z]+)((?:\s+[a-zA-Z0-9:-]+="[^"]*")*)\s*\/?>/g
  let rest = body.replace(tagRe, (m, tag, attrs) => {
    if (!TAGS.has(tag.toLowerCase())) throw new Error(`${label}: tag <${tag}> not allowed`)
    for (const [, n, v] of attrs.matchAll(/([a-zA-Z0-9:-]+)="([^"]*)"/g)) {
      if (!ATTRS.has(n.toLowerCase())) throw new Error(`${label}: attr ${n} not allowed`)
      if (/url\(\s*(?!#)|^(https?:|data:)/i.test(v)) throw new Error(`${label}: external ref in ${n}`)
    }
    return ''
  })
  if (rest.trim()) throw new Error(`${label}: unparsed content ${rest.slice(0, 40)}`)
  return body
}

const sets = {}
const out = {}
for (const [id, [pkg, name]] of Object.entries(WANTED)) {
  sets[pkg] ??= {
    json: JSON.parse(readFileSync(require.resolve(`@iconify-json/${pkg}/icons.json`), 'utf8')),
    meta: require(`@iconify-json/${pkg}/package.json`),
  }
  const { json } = sets[pkg]
  const icon = json.icons[name]
  if (!icon) throw new Error(`${pkg}/${name} missing`)
  const w = icon.width ?? json.width ?? 16
  const h = icon.height ?? json.height ?? 16
  out[id] = { vb: `0 0 ${w} ${h}`, body: sanitize(icon.body, `${pkg}/${name}`) }
}
// Vetted official brand SVGs (see scripts/brand-logos/SOURCES.md): <id>.svg, root attributes other than viewBox are dropped.
const dir = new URL('./brand-logos/', import.meta.url)
for (const f of readdirSync(dir).filter((n) => n.endsWith('.svg'))) {
  const raw = readFileSync(new URL(f, dir), 'utf8').replace(/<\?xml[^>]*\?>/g, '').trim()
  const m = raw.match(/^<svg([^>]*)>([\s\S]*)<\/svg>$/)
  const vb = m?.[1].match(/viewBox="([^"]+)"/)?.[1]
  if (!m || !vb) throw new Error(`${f}: no root svg/viewBox`)
  out[f.slice(0, -4)] = { vb, body: sanitize(m[2].replace(/>\s+</g, '><').trim(), f) }
}
const srcs = Object.entries(sets).map(([p, s]) => `@iconify-json/${p}@${s.meta.version} (${s.meta.license?.spdx ?? s.meta.license})`).join(', ')
const header = `// GENERATED by frontend/scripts/gen-app-logos-extra.mjs. Do not edit; regenerate with \`npm --prefix frontend run logos\`.
// Sources: ${srcs}. Plus official SVGs from each brand's own domain (scripts/brand-logos/SOURCES.md). Bodies sanitized (svg/g/path/shape/gradient only, no scripts, styles or external refs).
`
writeFileSync(new URL('../src/app-logos-extra.ts', import.meta.url), `${header}export const EXTRA_LOGOS: Record<string, { vb: string; body: string }> = ${JSON.stringify(out, null, 1)}\n`)
console.log('wrote', Object.keys(out).length, 'logos;', srcs)
